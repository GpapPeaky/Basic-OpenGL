    "    RZ[1][0] = sz; RZ[1][1] =  cz;\n"
    "\n"
    "    // Combined rotation\n"
    "    mat4 R = RZ * RY * RX;\n"
    "\n"
    "    // Translation\n"
    "    mat4 T = mat4(1.0);\n"
    "    T[3][0] = uTrans.x;\n"
    "    T[3][1] = uTrans.y;\n"
    "    T[3][2] = uTrans.z;\n"
    "\n"
    "    return T * R * S;\n"
    "}\n"
    "\n"
    "void main()\n"
    "{\n"
    "    mat4 model = buildModel();\n"
    "    gl_Position = uProj * uView * model * vec4(aPos, 1.0);\n"
    "}\n";

