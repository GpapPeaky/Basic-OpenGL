std::string OGLS_TRS_MVP_Lit_Blinn_Phong_Texture_AttenuatedF =
    "#version 410 core\n"
    "\n"
    "in vec2 TexCoord;\n"
    "in vec3 FragPos;\n"
    "in vec3 Normal;\n"
    "\n"
    "out vec4 FragColor;\n"
    "\n"
    // Light
    "uniform vec3 uLightDir;\n"             // Point light, not directional!
    "uniform vec3 uLightColor;\n"
    "uniform float uLightIntensity;\n"
    // Material
    "uniform vec3 uMatAmbientColor;\n"
    "uniform vec3 uMatDiffuseColor;\n"
    "uniform vec3 uMatSpecularColor;\n"
    "uniform vec3 uMatEmitColor;\n"
    "uniform float uMatEmitIntensity;\n"
    "uniform float uMatShininess;\n"
    "\n"
    "uniform sampler2D ourTexture;\n"
    "\n"
    "void main()\n"
    "{\n"
    "    vec3 norm = normalize(Normal);\n"
    "    vec3 lightDir = uLightDir - FragPos;\n"
    "    float distance = length(lightDir);\n"
    "    lightDir = normalize(lightDir);\n"
    "\n"
    "    // Attenuation (classic quadratic)\n"
    "    float attenuation = 1.0 / (distance * distance);\n"
    "\n"
    "    // Diffuse lighting\n"
    "    float diff = max(dot(norm, lightDir), 0.0);\n"
    "\n"
    "    // Specular lighting (Blinn-Phong)\n"
    "    vec3 viewDir = normalize(-FragPos); // camera at origin\n"
    "    vec3 halfwayDir = normalize(lightDir + viewDir);\n"
    "    float spec = pow(max(dot(norm, halfwayDir), 0.0), uMatShininess);\n"
    "\n"
    "    // Texture\n"
    "    vec3 texColor = texture(ourTexture, 1.0 - TexCoord).rgb;\n"
    "\n"
    "    // Combine material, texture, and lighting\n"
    "    vec3 ambient = uMatAmbientColor * texColor;\n"
    "    vec3 diffuse = uMatDiffuseColor * diff * texColor;\n"
    "    vec3 specular = uMatSpecularColor * spec;\n"
    "    vec3 emissive = uMatEmitColor * uMatEmitIntensity;\n"
    "\n"
    "    vec3 result = (ambient + diffuse + specular + emissive) * uLightIntensity * attenuation;\n"
    "    result *= uLightColor;\n"
    "\n"
    "    FragColor = vec4(result, 1.0);\n"
    "}\n";

